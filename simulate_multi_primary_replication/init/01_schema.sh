#!/bin/bash
# Runs once on each node's first boot. The schema is identical on both nodes except
# for the identity START value, which comes from $NODE_ID (1 or 2). Logical
# replication does NOT replicate DDL, so every node must create its own tables.
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    -- CONFLICT AVOIDANCE: each node generates ids from a disjoint sequence.
    -- node_a → 1, 11, 21 ...   node_b → 2, 12, 22 ...   (room for 10 nodes)
    -- Concurrent INSERTs on different nodes can therefore never collide on the key.
    CREATE TABLE orders (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH ${NODE_ID} INCREMENT BY 10) PRIMARY KEY,
        item       TEXT NOT NULL,
        written_on TEXT NOT NULL DEFAULT current_setting('cluster_name'),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    -- A row both nodes may UPDATE concurrently — the source of real conflicts.
    -- updated_at/updated_by carry the version information used by last-writer-wins.
    CREATE TABLE accounts (
        id         INT PRIMARY KEY,
        owner      TEXT NOT NULL,
        balance    NUMERIC(12, 2) NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
        updated_by TEXT NOT NULL DEFAULT current_setting('cluster_name')
    );

    -- LAST-WRITER-WINS guard. When the apply worker brings in a remote UPDATE that
    -- is OLDER than what we already have, skip it (RETURN NULL). Ties are broken
    -- deterministically by node name so both nodes make the same choice.
    CREATE FUNCTION lww_guard() RETURNS trigger LANGUAGE plpgsql AS \$\$
    BEGIN
        IF (NEW.updated_at, NEW.updated_by) < (OLD.updated_at, OLD.updated_by) THEN
            RAISE LOG 'lww_guard: skipping stale update of accounts.id=% from %', OLD.id, NEW.updated_by;
            RETURN NULL;
        END IF;
        RETURN NEW;
    END
    \$\$;

    CREATE TRIGGER accounts_lww BEFORE UPDATE ON accounts
        FOR EACH ROW EXECUTE FUNCTION lww_guard();
    -- Start disabled: the demo first shows what happens WITHOUT a resolution
    -- strategy, then enables it as a REPLICA trigger (fires only in the apply worker).
    ALTER TABLE accounts DISABLE TRIGGER accounts_lww;

    -- Every node publishes both tables. Subscriptions are created by the Go program
    -- because they need the peer's network address and must not run in a transaction.
    CREATE PUBLICATION pub_app FOR TABLE orders, accounts;
EOSQL

echo "node ${NODE_ID}: schema + publication created"
