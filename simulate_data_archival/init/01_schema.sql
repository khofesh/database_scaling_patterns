-- DATA ARCHIVAL: move rows nobody queries day-to-day (old, closed orders) out of the
-- hot table into an archive table tuned for cold data, and eventually out of the
-- database into cheap compressed files — while keeping a way to get them back.

-- ── Hot table: tuned for frequent reads AND updates ─────────────────────────
-- fillfactor 90 leaves room in each page so updates can be HOT (heap-only tuple)
-- updates that don't touch indexes.
CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT         NOT NULL,
    status      TEXT        NOT NULL,
    total       NUMERIC(10, 2) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    details     TEXT        NOT NULL      -- ~600 bytes of order JSON/notes
) WITH (fillfactor = 90);
CREATE INDEX orders_created_at_idx ON orders (created_at);
CREATE INDEX orders_customer_idx   ON orders (customer_id, created_at DESC);
CREATE INDEX orders_status_idx     ON orders (status);

-- ── Archive table: same columns, different storage parameters ───────────────
--   fillfactor 100            archived rows are never updated: pack pages full
--   COMPRESSION lz4           values big enough to be TOASTed (> ~2 KB rows) are
--                             compressed with lz4: faster than the default pglz
--   autovacuum insert tuning  insert-only table: vacuum mainly to set the
--                             visibility map, not to chase dead tuples
--   only two indexes          archive queries are by id or customer, nothing else
CREATE TABLE orders_archive (
    id          BIGINT PRIMARY KEY,
    customer_id INT         NOT NULL,
    status      TEXT        NOT NULL,
    total       NUMERIC(10, 2) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    details     TEXT COMPRESSION lz4 NOT NULL,
    archived_at TIMESTAMPTZ NOT NULL DEFAULT now()
) WITH (fillfactor = 100, autovacuum_vacuum_insert_scale_factor = 0.5);
CREATE INDEX orders_archive_customer_idx ON orders_archive (customer_id, created_at DESC);

-- Transparent retrieval: one relation spanning hot + archive.
CREATE VIEW orders_all AS
    SELECT id, customer_id, status, total, created_at, details, false AS archived FROM orders
    UNION ALL
    SELECT id, customer_id, status, total, created_at, details, true FROM orders_archive;

-- (Re)generates 3 years of orders: 400k rows, newest are 'open'/'shipped', older
-- ones 'delivered'. Called here and by the demo to reset between runs.
CREATE PROCEDURE seed_orders() LANGUAGE sql AS $$
    TRUNCATE orders, orders_archive;
    INSERT INTO orders (id, customer_id, status, total, created_at, details)
    SELECT g,
           g % 20000,
           CASE WHEN g > 396000 THEN (ARRAY['open', 'shipped'])[1 + g % 2] ELSE 'delivered' END,
           round((random() * 300 + 5)::numeric, 2),
           now() - interval '3 years' + g * (interval '3 years' / 400000),
           '{"items":[' || repeat('{"sku":"SKU-' || (g % 997) || '","qty":1,"note":"gift wrap please"},', 9)
               || '{}],"shipping":"standard"}'
    FROM generate_series(1, 400000) g;
    SELECT setval(pg_get_serial_sequence('orders', 'id'), 400000);
$$;

CALL seed_orders();
VACUUM ANALYZE;
